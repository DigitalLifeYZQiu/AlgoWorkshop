// 洛谷 T590312「见」
// 题意：n×n 网格，每格有高度 h[i][j] 的柱子。求四个方向"能看到多少根柱子"：
//       l_i（第 i 行从左看）、r_i（第 i 行从右看）、u_i（第 i 列从上往下看）、d_i（第 i 列从下往上看）。
// 规则：一根更远的柱子，若高度不超过某根更近的柱子，就看不到。
// 思路："可见"等价于"严格高于该方向前面所有柱子"，即"严格前缀最大值"的记录数；
//       四个方向各扫描一遍，数"打破历史最高纪录"的次数即可。
//

#include <iostream>

using namespace std;

int n;
int h[105][105];                // 柱子高度（n <= 100）
int l[105], r[105], u[105], d[105];   // 四个方向的可视柱子数

int main()
{
    cin >> n;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            cin >> h[i][j];
        }
    }

    // ---------- 每行的 l（左→右）和 r（右→左） ----------
    for (int i = 1; i <= n; i++)
    {
        int mx = 0;                    // 当前方向已看到的最高柱子（高度 >= 1，初始 0 足够）
        for (int j = 1; j <= n; j++)
        {
            if (h[i][j] > mx)          // 严格高于前面所有柱子 → 可见
            {
                l[i]++;
                mx = h[i][j];          // 更新"最高纪录"
            }
        }

        mx = 0;
        for (int j = n; j >= 1; j--)   // 从右往左扫
        {
            if (h[i][j] > mx)
            {
                r[i]++;
                mx = h[i][j];
            }
        }
    }

    // ---------- 每列的 u（上→下）和 d（下→上） ----------
    for (int j = 1; j <= n; j++)
    {
        int mx = 0;
        for (int i = 1; i <= n; i++)   // 从上往下扫
        {
            if (h[i][j] > mx)
            {
                u[j]++;
                mx = h[i][j];
            }
        }

        mx = 0;
        for (int i = n; i >= 1; i--)   // 从下往上扫
        {
            if (h[i][j] > mx)
            {
                d[j]++;
                mx = h[i][j];
            }
        }
    }

    // 输出：每行四个数 l_i, r_i, u_i, d_i
    for (int i = 1; i <= n; i++)
    {
        cout << l[i] << ' ' << r[i] << ' ' << u[i] << ' ' << d[i] << '\n';
    }
    return 0;
}
